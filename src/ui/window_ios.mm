/**
 * @file        rex/ui/window_ios.mm
 * @brief       iOS/iPadOS backend for rex::ui::Window (UIKit + CAMetalLayer)
 *
 * Follows the structure of window_macos.mm with the pieces that have no iPad
 * equivalent removed: no resizable window, no menus, no cursor capture, no
 * runtime fullscreen transitions (the window always covers the screen), and
 * no keyboard/mouse events (input is physical game controllers via SDL3).
 */

